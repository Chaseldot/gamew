import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(__dirname, '..');
const repoRoot = resolve(siteRoot, '..');
const webExportPath = resolve(repoRoot, 'content/12-website-assets/web_export.json');
const generatorPath = resolve(repoRoot, 'scripts/build-site-data.mjs');
const dataPath = resolve(siteRoot, 'data.js');

test('site data is generated from structured website export', () => {
  assert.ok(existsSync(webExportPath), 'content/12-website-assets/web_export.json should exist');
  assert.ok(existsSync(generatorPath), 'scripts/build-site-data.mjs should exist');

  const webExport = JSON.parse(readFileSync(webExportPath, 'utf8'));
  for (const key of ['siteMeta', 'navPages', 'regions', 'factions', 'companions', 'questSamples', 'gallery']) {
    assert.ok(Object.hasOwn(webExport, key), `web export should include ${key}`);
  }

  const dataSource = readFileSync(dataPath, 'utf8');
  assert.match(dataSource, /Generated by scripts\/build-site-data\.mjs/, 'site/data.js should carry the generated-file banner');

  execFileSync(process.execPath, [generatorPath, '--check'], {
    cwd: repoRoot,
    stdio: 'pipe',
  });
});
